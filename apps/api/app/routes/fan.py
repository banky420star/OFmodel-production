class SubscribeRequest(BaseModel):
    plan_code: str


@router.post("/fan/subscription")
async def subscribe(
    payload: SubscribeRequest,
    user: AppUser = Depends(require_user),
    link: FanAccount = Depends(require_fan),
    db: AsyncSession = Depends(get_db),
):
    plan = (
        await db.execute(
            select(SubscriptionPlan).where(
                SubscriptionPlan.code == payload.plan_code,
                SubscriptionPlan.active.is_(True),
            )
        )
    ).scalar_one_or_none()
    if plan is None:
        raise HTTPException(404, "No such plan")

    try:
        result = await billing.subscribe(
            db, user_id=user.id, plan=plan, fan_id=link.fan_id
        )
    except billing.MoneyError as exc:
        if exc.code == "insufficient_funds":
            raise HTTPException(402, str(exc))
        raise HTTPException(400, str(exc))
    await db.commit()

    wallet = await _wallet(db, user.id)
    return {**result, "balance_minor": wallet.balance_minor or 0}


