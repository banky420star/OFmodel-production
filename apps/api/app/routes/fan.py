# ── helpers ───────────────────────────────────────────────────────────

async def _persona_for(db: AsyncSession, link: FanAccount) -> Persona:
    from uuid import UUID

    try:
        persona = await db.get(Persona, UUID(str(link.persona_id)))
    except ValueError:
        persona = None
    if persona is None:
        raise HTTPException(409, "The assigned persona no longer exists")
    return persona


async def _wallet(db: AsyncSession, user_id: str) -> Wallet:
    wallet = (
        await db.execute(select(Wallet).where(Wallet.user_id == user_id))
    ).scalar_one_or_none()
    if wallet is None:
        wallet = Wallet(user_id=user_id, balance_minor=0)
        db.add(wallet)
        await db.flush()
    return wallet


async def _product(db: AsyncSession, product_id: str) -> Product:
    product = await db.get(Product, product_id)
    if product is None:
        raise HTTPException(404, "That content does not exist")
    return product


def _start_provider_names() -> list[str]:
    """The providers a new conversation may be pinned to.

    A test fake has no chain and returns [], in which case the provider picks
    whatever it has configured.
    """
    provider = get_registry().resolve_optional("llm")
    return list(getattr(provider, "member_names", []) or [])


async def _conversation(db: AsyncSession, link: FanAccount) -> FanConversation:
    """The fan's open thread, created on first use.

    Created with `served_by` already chosen, by rotating on how many
    conversations this fan has had — so the two live models genuinely share the
    live chat, while a single conversation never hears two voices. See
    app/providers/fallback_llm.py.
    """
    row = (
        await db.execute(
            select(FanConversation)
            .where(
                FanConversation.fan_id == link.fan_id,
                FanConversation.status == "open",
            )
            .order_by(FanConversation.created_at.desc())
            .limit(1)
        )
    ).scalars().first()
    if row is not None:
        return row

    previous = (
        await db.execute(
            select(func.count()).select_from(FanConversation).where(
                FanConversation.fan_id == link.fan_id
            )
        )
    ).scalar() or 0

    names = _start_provider_names()
    served_by = names[previous % len(names)] if names else ""

    row = FanConversation(
        fan_id=link.fan_id, persona_id=str(link.persona_id), served_by=served_by
    )
    db.add(row)
    await db.flush()
    return row


async def _thread_messages(db: AsyncSession, fan_id: str, limit: int = 60) -> list[dict]:
    # The tiebreak is load-bearing. A fan's message and her reply are written
    # in the same transaction, and were written with the same `created_at`, so
    # the database was free to return them in either order — the thread could
    # render as her answering before the question. Ordering by created_at and
    # then inbound-first makes the order defined even for the rows already
    # written that way. (The writer now also stamps the reply a microsecond
    # later; this handles the rows that predate that.)
    rows = (
        await db.execute(
            text(
                "SELECT id, direction, content, message_type, is_ai_generated, "
                "is_ppv, ppv_price, ppv_unlocked, intent, metadata_json, created_at "
                "FROM chat_messages WHERE fan_id = :fid "
                "ORDER BY created_at DESC, (direction = 'inbound') ASC "
                "LIMIT :limit"
            ),
            {"fid": fan_id, "limit": limit},
        )
    ).fetchall()

    out = []
    for row in reversed(rows):
        metadata = row[9]
        if isinstance(metadata, str):
            try:
                metadata = json.loads(metadata or "{}")
            except json.JSONDecodeError:
                metadata = {}
        out.append({
            "id": row[0],
            "direction": row[1],
            "content": row[2],
            "message_type": row[3],
            "is_ai_generated": bool(row[4]),
            "is_ppv": bool(row[5]),
            "ppv_price": row[6],
            "ppv_unlocked": bool(row[7]),
            "intent": row[8],
            "served_by": (metadata or {}).get("served_by", ""),
            "created_at": row[10].isoformat() if hasattr(row[10], "isoformat") else str(row[10]),
        })
    return out


async def _log_access(
    db: AsyncSession, *, user_id: str | None, product_id: str | None,
    allowed: bool, reason: str,
) -> None:
    db.add(AccessEvent(
        user_id=user_id, product_id=product_id, allowed=allowed, reason=reason
    ))
    await db.flush()


