"""Persona Studio — the fan-facing API.

Everything a paying visitor can reach. Every route requires a session cookie
(`require_user` / `require_fan`), and every route writes an audit row, so
`GET /fan/activity` is a real record of what happened rather than a summary
assembled after the fact.

Three properties this surface is built to have, in order of importance:

  1. **Nothing is invented.** If no LLM answers, the chat endpoint returns 503.
     There is no fallback text anywhere in this file.
  2. **Money moves once.** Unlocks are idempotent on the ledger's
     `ppv:{user}:{product}` key *and* on a unique constraint on entitlements.
  3. **Access is checked at serve time.** The media route re-asks the
     entitlements table on every request; a URL that worked yesterday does not
     work for someone who never paid.
"""

