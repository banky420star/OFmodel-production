@router.get("/fan/products")
async def list_products(
    user: AppUser = Depends(require_user),
    link: FanAccount = Depends(require_fan),
    db: AsyncSession = Depends(get_db),
):
    rows = (
        await db.execute(
            select(Product)
            .where(Product.persona_id == str(link.persona_id),
                   Product.status == "published")
            .order_by(Product.price_minor, Product.created_at)
        )
    ).scalars().all()

    subscription = await active_subscription(db, user.id)
    products = []
    for product in rows:
        allowed, reason = await check_access(
            db, user_id=user.id, product=product
        )
        media_count = (
            await db.execute(
                select(func.count()).select_from(ProductMedia).where(
                    ProductMedia.product_id == product.id
                )
            )
        ).scalar() or 0
        products.append({
            "id": product.id,
            "title": product.title,
            "description": product.description or "",
            "price_minor": product.price_minor,
            "price_display": f"{product.price_minor / 100:.2f}",
            "kind": product.kind,
            "is_adult": bool(product.is_adult),
            "unlocked": allowed,
            "reason": reason,
            "min_tier_rank": product.min_tier_rank,
            "media_count": media_count,
            "cover_url": f"/api/v1/fan/content/{product.id}/media/0" if media_count else "",
        })

    return {
        "products": products,
        "subscription": (
            {"plan_code": subscription.plan_code, "rank": subscription.plan_rank}
            if subscription else None
        ),
        "disclosure": AI_DISCLOSURE,
    }


@router.post("/fan/products/{product_id}/unlock")
async def unlock(
    product_id: str,
    user: AppUser = Depends(require_user),
    link: FanAccount = Depends(require_fan),
    db: AsyncSession = Depends(get_db),
):
    """Buy one product. Clicking twice charges once."""
    product = await _product(db, product_id)

    try:
        result = await billing.unlock_ppv(
            db, user_id=user.id, product=product, fan_id=link.fan_id
        )
    except billing.MoneyError as exc:
        if exc.code == "insufficient_funds":
            raise HTTPException(402, str(exc))
        raise HTTPException(400, str(exc))

    await db.commit()
    wallet = await _wallet(db, user.id)
    return {
        **result,
        "balance_minor": wallet.balance_minor or 0,
        "unlocked": True,
        "media_url": f"/api/v1/fan/content/{product.id}/media/0",
    }


@router.get("/fan/content/{product_id}")
async def get_content(
    product_id: str,
    user: AppUser = Depends(require_user),
    db: AsyncSession = Depends(get_db),
):
    product = await _product(db, product_id)
    allowed, reason = await check_access(db, user_id=user.id, product=product)
    await _log_access(
        db, user_id=user.id, product_id=product.id,
        allowed=allowed, reason=reason,
    )
    await db.commit()

    if not allowed:
        raise HTTPException(402, "Not unlocked")

    media = (
        await db.execute(
            select(ProductMedia)
            .where(ProductMedia.product_id == product.id)
            .order_by(ProductMedia.position, ProductMedia.created_at)
        )
    ).scalars().all()

    return {
        "id": product.id,
        "title": product.title,
        "description": product.description or "",
        "kind": product.kind,
        "disclosure": AI_DISCLOSURE,
        "media": [
            {
                "index": index,
                "caption": item.caption or "",
                "url": f"/api/v1/fan/content/{product.id}/media/{index}",
            }
            for index, item in enumerate(media)
        ],
    }


@router.get("/fan/content/{product_id}/media/{index}")
async def serve_media(
    product_id: str,
    index: int,
    user: AppUser = Depends(require_user),
    db: AsyncSession = Depends(get_db),
):
    """Serve one file — but only if this user is entitled to it, right now.

    The entitlement is re-checked on every request rather than trusted from the
    listing page, and denials are logged. `private, no-store` keeps it out of
    shared caches, because the same URL is a 402 for the next person.
    """
    product = await _product(db, product_id)
    allowed, reason = await check_access(db, user_id=user.id, product=product)
    await _log_access(
        db, user_id=user.id, product_id=product.id,
        allowed=allowed, reason=reason,
    )
    await db.commit()

    if not allowed:
        raise HTTPException(402, "Not unlocked")

    media = (
        await db.execute(
            select(ProductMedia)
            .where(ProductMedia.product_id == product.id)
            .order_by(ProductMedia.position, ProductMedia.created_at)
        )
    ).scalars().all()

    if index < 0 or index >= len(media):
        raise HTTPException(404, "No such item")

    item = media[index]
    file_path = (STORAGE_DIR / item.rel_path).resolve()

    # Path traversal guard. rel_path comes from the database, but it is written
    # by a seed script and could be edited, so the resolved path is checked to
    # still be inside storage/ before anything is opened.
    if not str(file_path).startswith(str(STORAGE_DIR.resolve())):
        raise HTTPException(403, "Refusing to serve a path outside storage")
    if not file_path.exists() or not file_path.is_file():
        raise HTTPException(404, "The file for this item is missing")

    media_type = {
        ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
        ".webp": "image/webp", ".mp4": "video/mp4",
    }.get(file_path.suffix.lower(), "application/octet-stream")

    return FileResponse(
        file_path,
        media_type=media_type,
        headers={
            "Cache-Control": "private, no-store",
            "X-AI-Generated": "true",
            "X-Simulated-Purchase": "true",
        },
    )


